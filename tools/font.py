def rows_of(ch):
    r = G[ch]
    out = []
    for row in r:
        v = 0
        for i, c in enumerate('.' + row + '.'):
            if c == '#': v |= 0x40 >> i
        out.append(v)
    out.append(0)
    return out

def build():
    data = []
    for code in range(0x20, 0x80):
        data += rows_of(chr(code))
    for m in M:
        assert len(m) == 8 and all(len(r) == 7 for r in m)
        for row in m:
            v = 0
            for i, c in enumerate(row):
                if c == '#': v |= 0x40 >> i
            data.append(v)
    return data  # (96 + 32) * 8 bytes; bit 6 = leftmost pixel

if __name__ == '__main__':
    data = build()
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', 'Heltec-AppleII', 'font.h')
    with open(out, 'w') as f:
        f.write('// Heltec-AppleII text font (original 7x8 glyphs, generated by tools/font.py)\n')
        f.write('// Glyphs for ASCII 0x20-0x7F, then 32 MouseText-style glyphs. 8 rows each, bit 6 = leftmost pixel.\n')
        f.write('#pragma once\n#include <stdint.h>\nstatic const uint8_t A2_FONT[%d] = {\n' % len(data))
        for i in range(0, len(data), 16):
            f.write('  ' + ','.join('0x%02X' % b for b in data[i:i + 16]) + ',\n')
        f.write('};\n')
    print('base64:', __import__('base64').b64encode(bytes(data)).decode())
